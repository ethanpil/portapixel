// glyphCols and glyphRows are the size of one letter. advance adds one empty
// column between two letters.
const (
	glyphCols = 5
	glyphRows = 7
	advance   = glyphCols + 1
)

// textWidth gives the width of the text in pixels at this scale.
func textWidth(text string, scale int) int {
	if text == "" {
		return 0
	}
	return (len(text)*advance - 1) * scale
}

// drawText paints the text with the top left corner at x and y.
//
// A large letter gets a gap of one pixel between its squares and a round corner.
// A small letter gets full squares, because a gap at that size makes the words
// hard to read on a screen that a person looks at from far away.
func drawText(img *image.RGBA, x, y int, text string, scale int, c color.RGBA, alpha float64) {
	gap, radius := 0.0, 0.0
	if scale >= 8 {
		gap = 1
		radius = (float64(scale) - gap) * 0.28
	}
	for i, r := range text {
		rows, ok := font[r]
		if !ok {
			continue // a letter that the font has no picture for stays empty
		}
		left := float64(x + i*advance*scale)
		for row, line := range strings.Split(rows, "/") {
			for col, place := range line {
				if place != '#' {
					continue
				}
				px := left + float64(col*scale)
				py := float64(y + row*scale)
				fillRound(img, px, py, px+float64(scale)-gap, py+float64(scale)-gap, radius, c, alpha)
			}
		}
	}
}
